-- Website leads: stored first, then handed out one at a time to the brokers an
-- admin has switched on, each under their own website daily limit.
--
-- WHY NOT THE FACEBOOK ROUTE. A Meta lead has a form, and lead_form maps the
-- form to a group; assign_lead then rotates inside that group. The website has
-- no form to map. Rotating website leads across GROUPS was the July design, and
-- it was dropped because a group of one broker would take the same share as a
-- group of five — the one-person group gets buried in website leads on top of
-- its Facebook ones. The admin picks the brokers instead, by hand, on the
-- Website leads screen.
--
-- A SEPARATE SYSTEM, deliberately. Nothing below reads or writes lead_delivery,
-- which is what the Facebook cap counts and what the lead-cost trigger (0088)
-- charges on. So a website lead neither uses up a broker's Facebook allowance
-- nor costs them anything, and the Facebook route cannot be disturbed by a bug
-- here. The price is that the broker-availability rules are written twice —
-- here and in assign_lead (0082). A rule changed in one must be changed in the
-- other; both copies say so.
--
-- STORE FIRST, ASSIGN LATER. The submission is written to webhook_event the
-- moment it arrives (status 'waiting'), and only this migration's drain turns
-- it into a lead. A lead row therefore exists only once it has a broker: there
-- is never an unassigned website lead sitting in a group's pool.
--
-- ONE LOCK for the drain and for every change to a broker's switch or limit,
-- so a switch-off can never race an assignment that is already running.
--
-- APPLY BY HAND in the Supabase SQL editor, like every migration in this repo.
-- Staging first.

begin;


-- ── 1. webhook_event accepts website submissions ──────────────────────────
--
-- 0007 declared both checks inline, so their names were generated by
-- Postgres. Found by definition rather than guessed by name: a guessed name
-- that did not match would make `drop constraint if exists` a silent no-op,
-- leave the old check in place, and the first real submission would fail.
do $$
declare
  v_name text;
begin
  for v_name in
    select conname from pg_constraint
    where conrelid = 'webhook_event'::regclass
      and contype = 'c'
      and (pg_get_constraintdef(oid) ilike '%source%'
           or pg_get_constraintdef(oid) ilike '%status%')
  loop
    execute format('alter table webhook_event drop constraint %I', v_name);
  end loop;
end $$;

alter table webhook_event add constraint webhook_event_source_check
  check (source in ('meta', 'tiktok', 'website'));

-- 'waiting' is the website's own state: stored, no broker free yet. It is
-- NOT 'received', on purpose — the Meta retry drain sweeps stale 'received'
-- rows and 'failed' rows with a next_retry_at, and a website row must never be
-- handed to the Meta ingester. A website row is 'waiting', 'processed', or
-- 'failed' with next_retry_at null, so neither of its queries can see one.
alter table webhook_event add constraint webhook_event_status_check
  check (status in ('received', 'processed', 'failed', 'waiting'));

-- The drain's exact read: the waiting website queue, oldest first.
create index idx_webhook_event_website_waiting
  on webhook_event (created_at, id)
  where source = 'website' and status = 'waiting';


-- ── 2. Who takes website leads, and how many a day ────────────────────────
--
-- A row only for brokers an admin has touched. No row means off, which is
-- also every broker's state the day this ships: nobody receives a website
-- lead until an admin switches them on.
create table website_broker_setting (
  broker_id uuid primary key references broker(id) on delete cascade,
  is_on boolean not null default false,
  -- SEPARATE from broker.daily_cap, which stays the Facebook limit. Neither
  -- counts the other's leads.
  daily_cap int not null default 0 check (daily_cap >= 0),
  updated_at timestamptz not null default now()
);

alter table website_broker_setting enable row level security;

create trigger trg_website_broker_setting_updated_at
  before update on website_broker_setting
  for each row execute function set_updated_at();


-- ── 3. Whose turn it is ───────────────────────────────────────────────────
--
-- One row. The broker who got the last website lead; the next goes to the
-- first eligible broker after them, by id, wrapping — the same turn-taking
-- rule broker_group_rotation uses inside a group, across everyone here.
create table website_rotation_state (
  id int primary key default 1 check (id = 1),
  -- set null, not restrict: deleting a broker must not be blocked by having
  -- once been last in line. A null pointer just starts the turn from the top.
  last_broker_id uuid references broker(id) on delete set null
);

insert into website_rotation_state (id) values (1);

alter table website_rotation_state enable row level security;


-- ── 4. The website's own delivery log ─────────────────────────────────────
--
-- What the website daily limit counts, exactly as lead_delivery is what the
-- Facebook cap counts. Kept apart so neither limit can see the other's leads
-- and so no lead-cost row is ever written for a website lead.
create table website_lead_delivery (
  lead_id uuid primary key references lead(id) on delete cascade,
  broker_id uuid not null references broker(id),
  delivered_at timestamptz not null default now()
);

create index idx_website_lead_delivery_broker
  on website_lead_delivery (broker_id, delivered_at);

alter table website_lead_delivery enable row level security;


-- ── 5. Reading the submission ─────────────────────────────────────────────
--
-- The website sends its OWN vocabulary (coverage 'auto-home', history 'none'
-- or '3-plus'); these turn it into what a broker reads on the lead.
--
-- COVERAGE IS NOT WRITTEN TO combined_policy_type, deliberately. Choosing a
-- policy type is not just a column: services/lead.py::set_policy_type creates
-- the applicant and the Primary property at the same time, and re-picking the
-- value already set is a no-op. A lead born with the column filled would have
-- the value and never the rows, and the broker's obvious fix — pick it again —
-- would do nothing. So the customer's choice arrives as an answer, and the
-- broker sets the policy type the same way they do for every Meta lead.

create or replace function website_coverage_label(p_coverage text)
returns text as $$
begin
  return case p_coverage
    when 'auto'        then 'Auto'
    when 'home'        then 'Home'
    when 'tenant'      then 'Tenant'
    when 'auto-home'   then 'Auto + Home'
    when 'auto-tenant' then 'Auto + Tenant'
  end;
end;
$$ language plpgsql immutable;

create or replace function website_history_label(p_value text)
returns text as $$
begin
  return case p_value
    when 'none'   then 'None'
    when '1'      then '1'
    when '2'      then '2'
    when '3-plus' then '3+'
  end;
end;
$$ language plpgsql immutable;

-- The answers a broker sees on the lead, keyed by the words they read there.
-- LeadHeader.tsx prints every extra_data entry, so this is the whole display:
-- no screen change is needed for website leads.
--
-- ONLY WHAT A BROKER ACTS ON. The consent notice, the page, the submission id
-- and the map coordinates stay in webhook_event.raw_payload, which is kept
-- forever — that is the record of what the customer was shown and when. Put on
-- the title bar they would crowd out the number a broker is trying to ring.
create or replace function website_lead_answers(p jsonb)
returns jsonb as $$
declare
  v_call text;
begin
  -- 'asap' or a one-hour Toronto slot, 'YYYY-MM-DDTHH'. Parsed and formatted
  -- in the same session time zone, so the hour printed is the hour sent.
  -- A malformed slot raises a data exception, which the drain treats as a
  -- permanently bad submission — intake validation should make that
  -- impossible, and failing loudly beats guessing a time to ring someone.
  if p->>'call_time' = 'asap' then
    v_call := 'ASAP';
  else
    v_call := to_char(
      to_timestamp(p->>'call_time', 'YYYY-MM-DD"T"HH24'),
      'Dy Mon FMDD, FMHH12 AM'
    );
  end if;

  return jsonb_strip_nulls(jsonb_build_object(
    'Coverage',                website_coverage_label(p->>'coverage'),
    'Address',                 nullif(p->>'address', ''),
    'Call time',               v_call,
    'Tickets (3 yrs)',         website_history_label(p->>'convictions'),
    'At-fault claims (6 yrs)', website_history_label(p->>'auto_claims'),
    'Home claims (6 yrs)',     website_history_label(p->>'home_claims')
  ));
end;
$$ language plpgsql stable;


-- ── 6. The drain ──────────────────────────────────────────────────────────
--
-- Walks the waiting queue oldest first and gives each submission to the next
-- eligible broker. Called after every submission, after every admin change on
-- the Website leads screen, and every 60 seconds (services/website_lead.py) —
-- the last one covers a broker unpausing and the daily reset.
--
-- STOPS AT THE FIRST SUBMISSION NOBODY CAN TAKE. It does not skip ahead to a
-- newer one: eligibility does not depend on the submission, so if nobody can
-- take the oldest, nobody can take the next either — and if that ever changes,
-- a newer lead must still not jump an older one.
--
-- FAILURE RULE, per submission:
--   * a data or integrity error (SQLSTATE class 22 or 23) means THIS
--     submission can never become a lead — a name that is missing, a date that
--     does not parse. It is marked 'failed' and the drain moves past it, so one
--     bad row cannot block the queue. The admin screen shows the failed count.
--   * ANY OTHER error is temporary as far as we can tell — a lock timeout, a
--     connection dropped. It is re-raised: the whole run rolls back, every
--     submission stays 'waiting', no WhatsApp is queued for the undone
--     assignments, and the next run tries again. Marking those 'failed' would
--     strand a good customer permanently over a blip.
create or replace function assign_waiting_website_leads()
returns jsonb as $$
declare
  v_event record;
  v_broker_id uuid;
  v_group_id uuid;
  v_last_broker_id uuid;
  v_last_reset_at timestamptz;
  v_lead_id uuid;
  v_payload jsonb;
  v_assigned int := 0;
  v_failed int := 0;
begin
  perform pg_advisory_xact_lock(hashtext('website_rotation'));

  select last_reset_at into v_last_reset_at from lead_allocation_state;

  for v_event in
    select id, raw_payload
    from webhook_event
    where source = 'website' and status = 'waiting'
    order by created_at, id
  loop
    select last_broker_id into v_last_broker_id
    from website_rotation_state where id = 1;

    -- WHO IS AVAILABLE. The same availability rules as assign_lead (0082) —
    -- active, not blocked by an admin, a broker not an admin, not self-paused,
    -- started, not in the Recycle Bin — plus this system's own two: switched
    -- on, and under the WEBSITE limit. A rule added to one copy must be added
    -- to the other.
    select b.id, b.group_id into v_broker_id, v_group_id
    from broker b
    join broker_group bg on bg.id = b.group_id
    join website_broker_setting ws on ws.broker_id = b.id
    where ws.is_on = true
      and bg.is_recycle_bin = false
      and b.is_active = true
      and b.is_blocked_by_admin = false
      and b.role = 'broker'
      and b.self_paused = false
      and (b.eligible_from is null or b.eligible_from <= now())
      and (
        select count(*) from website_lead_delivery d
        where d.broker_id = b.id and d.delivered_at >= v_last_reset_at
      ) < ws.daily_cap
    order by
      (b.id <= coalesce(v_last_broker_id, '00000000-0000-0000-0000-000000000000'::uuid)),
      b.id
    limit 1;

    if not found then
      exit;
    end if;

    v_payload := v_event.raw_payload;

    begin
      -- assigned_broker_id IN THE INSERT ITSELF. That is what fires the
      -- WhatsApp new-lead alert (trg_lead_whatsapp_assign, 0109/0111), which
      -- watches inserts and updates of that column. source is set in the same
      -- statement, so the alert's manual-lead check already sees 'website'.
      insert into lead (
        group_id, source, name, phone, email, extra_data,
        requested_at, assigned_broker_id, assigned_at, assigned_by
      ) values (
        v_group_id, 'website',
        v_payload->>'name', v_payload->>'phone', v_payload->>'email',
        website_lead_answers(v_payload),
        (v_payload->>'submitted_at')::timestamptz,
        v_broker_id, now(), 'system'
      )
      returning id into v_lead_id;

      -- The same trail assign_lead leaves, so the lead's history, custody and
      -- audit read identically whichever route brought it in.
      insert into website_lead_delivery (lead_id, broker_id)
      values (v_lead_id, v_broker_id);

      insert into lead_assignment (lead_id, broker_id, reason, reassigned_by)
      values (v_lead_id, v_broker_id, 'Initial Claim', null);

      insert into lead_stage_history (lead_id, broker_id, from_stage, to_stage)
      values (v_lead_id, v_broker_id, null, 'New');

      insert into audit_log (actor_broker_id, action, entity_type, entity_id, detail)
      values (null, 'lead_assigned', 'lead', v_lead_id::text,
              jsonb_build_object('broker_id', v_broker_id, 'tier', 'website',
                                 'actor', 'system', 'webhook_event_id', v_event.id));

      update website_rotation_state set last_broker_id = v_broker_id where id = 1;

      update webhook_event
      set status = 'processed', failure_reason = null, next_retry_at = null
      where id = v_event.id;

      v_assigned := v_assigned + 1;
    exception
      when data_exception or integrity_constraint_violation then
        -- Everything the block wrote is already undone, pointer included, so
        -- this broker keeps their turn for the next submission.
        update webhook_event
        set status = 'failed',
            failure_reason = sqlerrm,
            attempt_count = attempt_count + 1,
            next_retry_at = null
        where id = v_event.id;

        v_failed := v_failed + 1;
    end;
  end loop;

  return jsonb_build_object(
    'assigned', v_assigned,
    'failed', v_failed,
    'waiting', (select count(*) from webhook_event
                where source = 'website' and status = 'waiting')
  );
end;
$$ language plpgsql;


-- ── 7. Changing a broker's switch or limit ────────────────────────────────
--
-- UNDER THE DRAIN'S LOCK. A switch-off waits for any run already holding the
-- lock to finish, then commits; every run after that sees the broker as off.
-- The guarantee is exactly that: no NEW assignment once the switch-off has
-- committed. (An assignment the running drain had already made is a lead the
-- broker was given while still switched on, and stays theirs.)
--
-- Null leaves that field as it is, so the screen can send one field at a time.
create or replace function set_website_broker_setting(
  p_broker_id uuid,
  p_is_on boolean,
  p_daily_cap int
)
returns website_broker_setting as $$
declare
  v_row website_broker_setting;
begin
  perform pg_advisory_xact_lock(hashtext('website_rotation'));

  insert into website_broker_setting (broker_id, is_on, daily_cap)
  values (p_broker_id, coalesce(p_is_on, false), coalesce(p_daily_cap, 0))
  on conflict (broker_id) do update
    set is_on = coalesce(p_is_on, website_broker_setting.is_on),
        daily_cap = coalesce(p_daily_cap, website_broker_setting.daily_cap)
  returning * into v_row;

  return v_row;
end;
$$ language plpgsql;


-- ── 8. What the Website leads screen shows ────────────────────────────────
--
-- Every broker in every group (admins excluded, as they are from the
-- rotation), with their switch, limit, today's website count and whether they
-- are paused — plus the size of the waiting and failed queues. One call.
create or replace function website_lead_board()
returns jsonb as $$
declare
  v_last_reset_at timestamptz;
begin
  select last_reset_at into v_last_reset_at from lead_allocation_state;

  return jsonb_build_object(
    'waiting', (select count(*) from webhook_event
                where source = 'website' and status = 'waiting'),
    'failed',  (select count(*) from webhook_event
                where source = 'website' and status = 'failed'),
    'brokers', coalesce((
      select jsonb_agg(row_to_json(r) order by r.group_name, r.name)
      from (
        select
          b.id as broker_id,
          b.name,
          bg.id as group_id,
          bg.name as group_name,
          coalesce(ws.is_on, false) as is_on,
          coalesce(ws.daily_cap, 0) as daily_cap,
          (select count(*) from website_lead_delivery d
           where d.broker_id = b.id and d.delivered_at >= v_last_reset_at) as today,
          b.self_paused,
          b.is_blocked_by_admin,
          b.is_active
        from broker b
        join broker_group bg on bg.id = b.group_id
        left join website_broker_setting ws on ws.broker_id = b.id
        where b.role = 'broker'
          and b.is_archived = false
          and bg.is_recycle_bin = false
      ) r
    ), '[]'::jsonb)
  );
end;
$$ language plpgsql stable;


-- ── 9. The one Facebook-side change ───────────────────────────────────────
--
-- Recreated from 0082's body. The ONLY change is `and source <> 'website'`.
--
-- DEFENSIVE. The drain above never creates an unassigned website lead, and no
-- code path today returns a lead to the pool. (This comment first said an
-- admin could; review found no such path. Corrected in place.) If one ever
-- exists, this function (run by the daily reset and on unpause) would hand it
-- out by FACEBOOK rules — into lead_delivery, against the Facebook cap, with a
-- lead-cost charge. The other door, the admin POST /leads, refuses
-- source='website' in services/lead.py::create_lead.
create or replace function assign_pending_leads_for_group(p_group_id uuid)
returns void as $$
declare
  v_lead_id uuid;
begin
  -- THE LOCK, BEFORE THE LOOP — before the SELECT that reads the backlog, not
  -- merely before the assignment. A lock taken after the read would still let
  -- both callers act on the same stale list.
  --
  -- RE-ENTRANT, so nesting is safe: assign_lead takes this same lock inside
  -- this same transaction, and pg_advisory_xact_lock can be taken repeatedly
  -- by the holder. It cannot deadlock against itself, and every lock is
  -- released at transaction end whatever happens.
  perform pg_advisory_xact_lock(hashtext('broker_group_rotation'), hashtext(p_group_id::text));

  for v_lead_id in
    select id from lead
    where group_id = p_group_id
      and assigned_broker_id is null
      and source <> 'website'
    order by coalesce(requested_at, created_at) asc
  loop
    perform assign_lead(v_lead_id);
  end loop;
end;
$$ language plpgsql;

commit;


